use glam::Vec3;
use serde::{Deserialize, Serialize};
use std::collections::VecDeque;

/// Configuration defining movement dynamics, speeds, and forces.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PlayerPhysicsConfig {
    pub walk_speed: f32,
    pub run_speed: f32,
    pub acceleration: f32,
    pub friction: f32,
    pub gravity: f32,
    pub jump_impulse: f32,
    pub max_input_history: usize,
}

impl Default for PlayerPhysicsConfig {
    fn default() -> Self {
        Self {
            walk_speed: 4.0,
            run_speed: 8.0,
            acceleration: 30.0,
            friction: 20.0,
            gravity: 9.81,
            jump_impulse: 5.5,
            max_input_history: 256,
        }
    }
}

/// Discrete user input command payload for generating client prediction frames.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct InputCommand {
    pub delta_time: f32,
    pub forward: f32, // -1.0 (backward) to +1.0 (forward)
    pub strafe: f32,  // -1.0 (left) to +1.0 (right)
    pub jump: bool,
    pub sprint: bool,
    pub yaw: f32,   // Rotation around Y axis in radians
    pub pitch: f32, // Camera pitch angle in radians
    pub timestamp: f64,
}

impl Default for InputCommand {
    fn default() -> Self {
        Self {
            delta_time: 0.016,
            forward: 0.0,
            strafe: 0.0,
            jump: false,
            sprint: false,
            yaw: 0.0,
            pitch: 0.0,
            timestamp: 0.0,
        }
    }
}

/// A single discrete user input command generated by the client.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ClientInput {
    pub sequence: u32,
    pub timestamp: f64,
    pub delta_time: f32,
    pub forward: f32, // -1.0 (backward) to +1.0 (forward)
    pub strafe: f32,  // -1.0 (left) to +1.0 (right)
    pub jump: bool,
    pub sprint: bool,
    pub yaw: f32,   // Rotation around Y axis in radians
    pub pitch: f32, // Camera pitch angle in radians
}

/// The physical state of the player entity at a specific point in time.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct PlayerPhysicsState {
    pub sequence: u32,
    pub position: Vec3,
    pub velocity: Vec3,
    pub yaw: f32,
    pub pitch: f32,
    pub is_grounded: bool,
}

impl PlayerPhysicsState {
    pub fn new(position: Vec3) -> Self {
        Self {
            sequence: 0,
            position,
            velocity: Vec3::ZERO,
            yaw: 0.0,
            pitch: 0.0,
            is_grounded: true,
        }
    }
}

/// Client-side movement predictor providing zero-latency input evaluation
/// and buffering historical inputs for authoritative reconciliation.
#[derive(Debug, Clone)]
pub struct MovementPredictor {
    state: PlayerPhysicsState,
    config: PlayerPhysicsConfig,
    history: VecDeque<ClientInput>,
    next_sequence: u32,
}

impl MovementPredictor {
    pub fn new(initial_state: PlayerPhysicsState, config: PlayerPhysicsConfig) -> Self {
        Self {
            state: initial_state,
            config,
            history: VecDeque::with_capacity(256),
            next_sequence: 1,
        }
    }

    #[must_use]
    pub fn state(&self) -> &PlayerPhysicsState {
        &self.state
    }

    #[must_use]
    pub fn config(&self) -> &PlayerPhysicsConfig {
        &self.config
    }

    #[must_use]
    pub fn history(&self) -> &VecDeque<ClientInput> {
        &self.history
    }

    /// Simulates a single physics step deterministically from the given state and input.
    pub fn step_simulation(
        state: &mut PlayerPhysicsState,
        input: &ClientInput,
        config: &PlayerPhysicsConfig,
    ) {
        let dt = input.delta_time.clamp(0.001, 0.1);

        // Compute local movement desire vector
        let move_raw = Vec3::new(input.strafe, 0.0, input.forward);
        let move_len = move_raw.length();
        let move_dir_local = if move_len > 0.001 {
            move_raw / move_len
        } else {
            Vec3::ZERO
        };

        // Transform movement desire into world space using yaw
        let sin_yaw = input.yaw.sin();
        let cos_yaw = input.yaw.cos();
        // In SWG coordinate system: forward (+Z local) rotated by yaw: (sin_yaw, 0, cos_yaw)
        // Strafe (+X local) rotated by yaw: (cos_yaw, 0, -sin_yaw)
        let world_move_dir = Vec3::new(
            move_dir_local.x * cos_yaw + move_dir_local.z * sin_yaw,
            0.0,
            -move_dir_local.x * sin_yaw + move_dir_local.z * cos_yaw,
        );

        let target_speed = if input.sprint {
            config.run_speed
        } else {
            config.walk_speed
        };

        let target_horizontal_vel = world_move_dir * target_speed;

        // Apply acceleration or deceleration to horizontal velocity
        let mut horiz_vel = Vec3::new(state.velocity.x, 0.0, state.velocity.z);
        let vel_diff = target_horizontal_vel - horiz_vel;
        let diff_len = vel_diff.length();

        if diff_len > 0.001 {
            let accel_rate = if world_move_dir.length_squared() > 0.001 {
                config.acceleration
            } else {
                config.friction
            };
            let step = (accel_rate * dt).min(diff_len);
            horiz_vel += (vel_diff / diff_len) * step;
        }

        // Vertical physics (jump & gravity)
        let mut vert_vel = state.velocity.y;
        if state.is_grounded {
            if input.jump {
                vert_vel = config.jump_impulse;
                state.is_grounded = false;
            } else {
                vert_vel = 0.0;
            }
        } else {
            vert_vel -= config.gravity * dt;
        }

        // Position integration
        let new_velocity = Vec3::new(horiz_vel.x, vert_vel, horiz_vel.z);
        let mut new_position = state.position + new_velocity * dt;

        // Ground clamping (default flat plane Y=0 unless elevated)
        if new_position.y <= 0.0 {
            new_position.y = 0.0;
            state.is_grounded = true;
        }

        state.position = new_position;
        state.velocity = new_velocity;
        state.yaw = input.yaw;
        state.pitch = input.pitch;
        state.sequence = input.sequence;
    }

    /// Appends a new input command, immediately executes local prediction,
    /// and records it into history for future reconciliation.
    pub fn push_input(&mut self, cmd: InputCommand) -> (u32, PlayerPhysicsState) {
        let seq = self.next_sequence;
        self.next_sequence += 1;

        let input = ClientInput {
            sequence: seq,
            timestamp: cmd.timestamp,
            delta_time: cmd.delta_time,
            forward: cmd.forward,
            strafe: cmd.strafe,
            jump: cmd.jump,
            sprint: cmd.sprint,
            yaw: cmd.yaw,
            pitch: cmd.pitch,
        };

        Self::step_simulation(&mut self.state, &input, &self.config);

        self.history.push_back(input);
        while self.history.len() > self.config.max_input_history {
            self.history.pop_front();
        }

        (seq, self.state)
    }

    /// Sets the underlying physics state directly (used internally during reconciliation).
    pub(crate) fn set_state(&mut self, state: PlayerPhysicsState) {
        self.state = state;
    }

    /// Access mutable reference to history (used internally during reconciliation).
    pub(crate) fn history_mut(&mut self) -> &mut VecDeque<ClientInput> {
        &mut self.history
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_zero_latency_local_prediction() {
        let config = PlayerPhysicsConfig::default();
        let initial = PlayerPhysicsState::new(Vec3::new(10.0, 0.0, 10.0));
        let mut predictor = MovementPredictor::new(initial, config);

        // Player presses 'W' (forward = 1.0) with yaw = 0 (moving +Z)
        let (seq1, state1) = predictor.push_input(InputCommand {
            delta_time: 0.05,
            forward: 1.0,
            timestamp: 1000.0,
            ..Default::default()
        });
        assert_eq!(seq1, 1);
        assert!(
            state1.position.z > 10.0,
            "Player must immediately advance along Z without waiting for server"
        );
        assert!(state1.velocity.z > 0.0);
        assert_eq!(state1.position.x, 10.0);

        // Second tick continues advancing
        let (seq2, state2) = predictor.push_input(InputCommand {
            delta_time: 0.05,
            forward: 1.0,
            timestamp: 1000.05,
            ..Default::default()
        });
        assert_eq!(seq2, 2);
        assert!(state2.position.z > state1.position.z);
        assert_eq!(predictor.history().len(), 2);
    }

    #[test]
    fn test_sprint_velocity_scaling() {
        let config = PlayerPhysicsConfig::default();
        let mut walk_pred =
            MovementPredictor::new(PlayerPhysicsState::new(Vec3::ZERO), config.clone());
        let mut sprint_pred = MovementPredictor::new(PlayerPhysicsState::new(Vec3::ZERO), config);

        for i in 0..20 {
            walk_pred.push_input(InputCommand {
                delta_time: 0.05,
                forward: 1.0,
                sprint: false,
                timestamp: 1000.0 + f64::from(i) * 0.05,
                ..Default::default()
            });
            sprint_pred.push_input(InputCommand {
                delta_time: 0.05,
                forward: 1.0,
                sprint: true,
                timestamp: 1000.0 + f64::from(i) * 0.05,
                ..Default::default()
            });
        }

        assert!(
            sprint_pred.state().position.z > walk_pred.state().position.z * 1.5,
            "Sprinting must cover significantly more distance than walking"
        );
    }
}
